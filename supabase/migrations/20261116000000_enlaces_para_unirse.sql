-- Enlaces para unirse a la app (Ajustes → Invitar a la app): quien tenga cuenta copia un enlace y la
-- persona nueva crea su cuenta con su nombre, correo y contraseña. Cada enlace sirve para una
-- persona y vence a los 7 días. Solo el servidor lo usa (RLS activo y sin políticas).
create table if not exists enlaces_app (
  id         integer generated by default as identity primary key,
  token      text not null unique,
  creado_por uuid references miembros(usuario_id) on delete set null,
  creado     timestamptz not null default now(),
  vence      timestamptz not null default now() + interval '7 days',
  usado      timestamptz,
  usado_por  uuid references miembros(usuario_id) on delete set null
);
create index if not exists idx_enlaces_app_creado_por on enlaces_app(creado_por);
create index if not exists idx_enlaces_app_usado_por on enlaces_app(usado_por);
alter table enlaces_app enable row level security;
