-- Cuadernos: cada uno con sus propios datos (presupuesto, deudas, metas, listas, movimientos,
-- actividad) y su propia gente, con permiso de propietario, editor (lectura y escritura) o lector.
--
-- Aislamiento: la app abre cada petición en una transacción, fija el cuaderno con
-- set_config('app.cuaderno', id, true) y cambia al rol finanzas_app (sin BYPASSRLS). Las políticas
-- dejan ver y cambiar solo las filas de ese cuaderno, y cuaderno_id se llena solo al insertar.
-- Las tablas no llevan esquema fijo: la migración corre en el esquema actual.

create table if not exists cuadernos (
  id         integer generated by default as identity primary key,
  nombre     text not null,
  icono      text,
  creado_por uuid references miembros(usuario_id) on delete set null,
  creado     timestamptz not null default now()
);
create index if not exists idx_cuadernos_creado_por on cuadernos(creado_por);

-- Quién está en cada cuaderno y con qué permiso. Al quitar a alguien se desactiva (sus registros conservan el nombre).
create table if not exists cuaderno_miembros (
  cuaderno_id integer not null references cuadernos(id) on delete cascade,
  usuario_id  uuid not null references miembros(usuario_id) on delete cascade,
  permiso     text not null default 'editor' check (permiso in ('propietario','editor','lector')),
  activo      boolean not null default true,
  creado      timestamptz not null default now(),
  primary key (cuaderno_id, usuario_id)
);
create index if not exists idx_cuaderno_miembros_usuario on cuaderno_miembros(usuario_id);

-- Invitaciones por enlace (token secreto). Quien ya tiene cuenta con ese correo también la ve al entrar.
create table if not exists invitaciones (
  id           integer generated by default as identity primary key,
  cuaderno_id  integer not null references cuadernos(id) on delete cascade,
  correo       text not null,
  permiso      text not null check (permiso in ('editor','lector')),
  token        text not null unique,
  invitado_por uuid references miembros(usuario_id) on delete set null,
  creado       timestamptz not null default now(),
  vence        timestamptz not null default now() + interval '14 days',
  aceptada     timestamptz,
  aceptada_por uuid references miembros(usuario_id) on delete set null,
  rechazada    timestamptz
);
create index if not exists idx_invitaciones_cuaderno on invitaciones(cuaderno_id);
create index if not exists idx_invitaciones_correo on invitaciones(lower(correo));
create index if not exists idx_invitaciones_invitado_por on invitaciones(invitado_por);
create index if not exists idx_invitaciones_aceptada_por on invitaciones(aceptada_por);

-- Cuaderno de la petición en curso (nulo si no se fijó: entonces no se ve ni se inserta nada)
create or replace function app_cuaderno() returns integer
language sql stable set search_path = '' as $$
  select nullif(current_setting('app.cuaderno', true), '')::integer
$$;

-- Los datos que ya existían pasan a un primer cuaderno, con sus miembros (quien administra = propietario)
do $$
declare nuevo integer;
begin
  if exists (select 1 from periodos) and not exists (select 1 from cuadernos) then
    insert into cuadernos (nombre, creado_por)
    values (
      coalesce((select nullif(valor, '') from config where clave = 'hogar'), 'Mi hogar'),
      (select usuario_id from miembros where rol = 'admin' and activo order by creado limit 1)
    )
    returning id into nuevo;
    insert into cuaderno_miembros (cuaderno_id, usuario_id, permiso)
    select nuevo, usuario_id, case when rol = 'admin' then 'propietario' else 'editor' end from miembros where activo;
  end if;
end $$;

-- Cada tabla de datos pertenece a un cuaderno
do $$
declare
  t text;
  primero integer := (select min(id) from cuadernos);
begin
  foreach t in array array['config','periodos','categorias','rubros','valores','metas','listas','items','movimientos','actividad'] loop
    execute format('alter table %I add column if not exists cuaderno_id integer', t);
    execute format('update %I set cuaderno_id = $1 where cuaderno_id is null', t) using primero;
    execute format('alter table %I alter column cuaderno_id set default app_cuaderno()', t);
    execute format('alter table %I alter column cuaderno_id set not null', t);
    execute format('alter table %I add constraint %I foreign key (cuaderno_id) references cuadernos(id) on delete cascade', t, t || '_cuaderno_fk');
    execute format('create index if not exists %I on %I (cuaderno_id)', 'idx_' || t || '_cuaderno', t);
  end loop;
end $$;

-- Claves que antes eran únicas en toda la base ahora lo son dentro de cada cuaderno
alter table config drop constraint config_pkey;
alter table config add primary key (cuaderno_id, clave);

alter table valores drop constraint valores_periodo_id_fkey;
alter table periodos drop constraint periodos_pkey;
alter table periodos add primary key (cuaderno_id, id);
alter table valores add constraint valores_periodo_fk
  foreign key (cuaderno_id, periodo_id) references periodos(cuaderno_id, id) on delete cascade;

alter table categorias drop constraint categorias_nombre_key;
alter table categorias add constraint categorias_cuaderno_nombre_key unique (cuaderno_id, nombre);

alter table cuadernos         enable row level security;
alter table cuaderno_miembros enable row level security;
alter table invitaciones      enable row level security;

-- Rol con el que la app lee y escribe los datos de un cuaderno (no puede saltarse RLS)
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'finanzas_app') then
    create role finanzas_app nologin noinherit;
  end if;
end $$;
grant finanzas_app to postgres;

do $$
declare
  esquema text := current_schema();
  t text;
begin
  execute format('grant usage on schema %I to finanzas_app', esquema);
  execute format('grant execute on function %I.app_cuaderno() to finanzas_app', esquema);
  execute format('grant usage, select on all sequences in schema %I to finanzas_app', esquema);
  foreach t in array array['config','periodos','categorias','rubros','valores','metas','listas','items','movimientos','actividad'] loop
    execute format('grant select, insert, update, delete on %I to finanzas_app', t);
    execute format('drop policy if exists solo_su_cuaderno on %I', t);
    execute format('create policy solo_su_cuaderno on %I for all to finanzas_app using (cuaderno_id = app_cuaderno()) with check (cuaderno_id = app_cuaderno())', t);
  end loop;
end $$;
