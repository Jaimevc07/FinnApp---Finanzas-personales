-- Esquema de Finanzas Hogar en Postgres (Supabase).
-- Las tablas no llevan esquema fijo: se crean en el search_path actual (public en producción).
-- La app se conecta desde el servidor con el usuario postgres (por el pooler), así que RLS se
-- activa sin políticas: la API pública de Supabase (clave publicable/anon) no puede leer nada.

create table if not exists config (
  clave text primary key,
  valor text not null
);

create table if not exists periodos (
  id       text primary key,              -- AAAA-MM
  etiqueta text not null,                 -- "Dic 2026"
  cobro    text not null,                 -- "Cobro 30 Nov" (esquema a mes vencido)
  orden    integer not null
);

create table if not exists categorias (
  id      integer generated by default as identity primary key,
  nombre  text not null unique,
  seccion text not null check (seccion in ('ingreso','operativo','evento','deuda','ahorro')),
  control text,                           -- Fijo / Semi-fijo / Flexible
  orden   integer not null default 0,
  icono   text                            -- clave de lib/iconos.ts (nulo = según el nombre)
);

create table if not exists rubros (
  id           integer generated by default as identity primary key,
  categoria_id integer not null references categorias(id) on delete cascade,
  nombre       text not null,
  orden        integer not null default 0,
  saldo_usd    double precision,          -- deuda en dólares (celdas auto usan la TRM)
  saldo        double precision,          -- deuda en pesos al inicio del plan
  tasa         double precision,          -- interés mensual de la deuda (%)
  recurrente   integer not null default 1,-- 1 = todos los meses · 0 = solo los meses con valor
  icono        text,
  cupo         double precision,          -- cupo total si la deuda es una tarjeta de crédito
  cupo_de      integer references rubros(id) on delete set null -- usa el cupo de otra deuda (misma tarjeta)
);
create index if not exists idx_rubros_categoria on rubros(categoria_id);
create index if not exists idx_rubros_cupo_de on rubros(cupo_de);

create table if not exists valores (
  rubro_id   integer not null references rubros(id) on delete cascade,
  periodo_id text    not null references periodos(id) on delete cascade,
  valor      double precision not null default 0,
  auto       integer not null default 0,
  primary key (rubro_id, periodo_id)
);
create index if not exists idx_valores_periodo on valores(periodo_id);

create table if not exists metas (
  id               integer generated by default as identity primary key,
  nombre           text not null,
  detalle          text not null default '',
  objetivo         double precision not null default 0,
  periodo_objetivo text,                  -- AAAA-MM; nulo = último mes del plan
  modo             text not null default 'aportes' check (modo in ('aportes','caja')),
  ahorrado         double precision not null default 0,
  rubro_id         integer references rubros(id) on delete set null,
  orden            integer not null default 0,
  icono            text,
  pausada_desde    text,                  -- AAAA-MM desde el que no se aporta; nulo = activa
  aporte_pausado   double precision       -- aporte mensual que tenía al pausarla (para reanudar)
);
create index if not exists idx_metas_rubro on metas(rubro_id);

create table if not exists listas (
  id          integer generated by default as identity primary key,
  nombre      text not null,
  rubro_id    integer references rubros(id) on delete set null,
  presupuesto double precision not null default 0,
  orden       integer not null default 0,
  icono       text
);
create index if not exists idx_listas_rubro on listas(rubro_id);

create table if not exists items (
  id        integer generated by default as identity primary key,
  lista_id  integer not null references listas(id) on delete cascade,
  categoria text not null default '',
  producto  text not null,
  cantidad  double precision not null default 1,
  precio    double precision not null default 0,
  estado    text not null default 'Pendiente' check (estado in ('Pendiente','Comprado','Ajustar')),
  orden     integer not null default 0
);
create index if not exists idx_items_lista on items(lista_id);

create table if not exists movimientos (
  id          integer generated by default as identity primary key,
  fecha       text not null,              -- AAAA-MM-DD
  tipo        text not null check (tipo in ('ingreso','egreso')),
  descripcion text not null,
  categoria   text not null,
  medio       text not null,
  valor       double precision not null default 0,
  creado      timestamptz not null default now(),
  tarjeta_id  integer references rubros(id) on delete set null -- tarjeta de crédito usada
);
create index if not exists idx_movimientos_fecha on movimientos(fecha);
create index if not exists idx_movimientos_tarjeta on movimientos(tarjeta_id);

-- Solo el servidor (usuario postgres) accede a los datos: RLS activo y sin políticas.
alter table config      enable row level security;
alter table periodos    enable row level security;
alter table categorias  enable row level security;
alter table rubros      enable row level security;
alter table valores     enable row level security;
alter table metas       enable row level security;
alter table listas      enable row level security;
alter table items       enable row level security;
alter table movimientos enable row level security;
